def load_extra_locales() -> dict[str, dict[str, str]]:
    """Import additional locale tables from companion module if present."""
    try:
        from generate_l10n_translations import LOCALES  # type: ignore
        return LOCALES
    except Exception:
        return {}


def write_arb(locale: str, strings: dict[str, str], *, with_meta: bool) -> None:
    data: dict[str, object] = {"@@locale": locale}
    for key, value in strings.items():
        data[key] = value
        if with_meta and key in META:
            data[f"@{key}"] = META[key]
    path = OUT / f"app_{locale}.arb"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.name} ({len(strings)} keys)")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    missing = [k for k in EN if k not in TR]
    extra_tr = [k for k in TR if k not in EN]
    if missing or extra_tr:
        raise SystemExit(f"TR key mismatch missing={missing} extra={extra_tr}")

    write_arb("en", EN, with_meta=True)
    write_arb("tr", TR, with_meta=False)

    locales = load_extra_locales()
    for locale, table in locales.items():
        miss = [k for k in EN if k not in table]
        if miss:
            raise SystemExit(f"{locale} missing keys: {miss[:8]}... ({len(miss)} total)")
        write_arb(locale, table, with_meta=False)

    print(f"done. locales on disk: {sorted(p.name for p in OUT.glob('*.arb'))}")


if __name__ == "__main__":
    main()
