def main() -> None:
    for path in sorted(ROOT.glob("app_*.arb")):
        loc = path.stem[len("app_") :]
        patch = STRINGS.get(loc)
        if patch is None:
            print(f"skip {loc}")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        data.update(patch)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"patched {loc}")


if __name__ == "__main__":
    main()
